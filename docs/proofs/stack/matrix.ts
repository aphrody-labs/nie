// Stack import matrix: for each workspace (apps/*, packages/*, crates/*), how many source files
// import each library, plus its declared role. Usage: bun docs/proofs/stack/matrix.ts > matrix.md
import { readdirSync, existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

const TS_LIBS: Record<string, RegExp> = {
  elysia: /from ["']elysia["']|from ["']@elysiajs\//,
  hono: /from ["']hono["']/,
  next: /from ["']next(\/[^"']*)?["']/,
  kysely: /from ["']kysely["']/,
  "postgres.js": /from ["']postgres["']/,
  pg: /from ["']pg["']/,
  "bun:sql": /\bSQL\b[^;]*from ["']bun["']|from ["']bun["'][^;]*\bSQL\b/,
  drizzle: /from ["']drizzle-orm/,
  supabase: /from ["']@supabase\//,
  "bun:redis": /\bRedisClient\b[^;]*from ["']bun["']/,
  "npm redis": /from ["']redis["']|from ["']ioredis["']/,
  "bun:sqlite": /from ["']bun:sqlite["']/,
  "better-auth": /from ["']better-auth/,
  colyseus: /from ["']colyseus|from ["']@colyseus\//,
  "discord.js": /from ["']discord\.js["']/,
  react: /from ["']react["']/,
};
const RS_LIBS = ["axum", "actix-web", "hyper", "tokio", "sqlx", "tokio-postgres", "rusqlite", "redis", "r2d2", "bevy", "dioxus", "wgpu", "taffy", "serde_json", "reqwest"];

function files(dir: string, ext: RegExp, out: string[] = []): string[] {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (["node_modules", ".next", "target", "dist", "pkg"].includes(e.name)) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) files(p, ext, out);
    else if (ext.test(e.name)) out.push(p);
  }
  return out;
}

const rows: string[] = [];
const tsCols = Object.keys(TS_LIBS);
rows.push(`## TypeScript workspaces\n\n| workspace | role | files | ${tsCols.join(" | ")} |\n|---|---|---|${tsCols.map(() => "---").join("|")}|`);
for (const base of ["apps", "packages"]) {
  for (const ws of readdirSync(base)) {
    const pj = join(base, ws, "package.json");
    if (!existsSync(pj)) continue;
    const desc = (JSON.parse(readFileSync(pj, "utf8")).description ?? "").replace(/\|/g, "/").slice(0, 70);
    const src = files(join(base, ws), /\.(ts|tsx)$/);
    const counts = tsCols.map((c) => src.filter((f) => TS_LIBS[c]!.test(readFileSync(f, "utf8"))).length);
    rows.push(`| ${base}/${ws} | ${desc} | ${src.length} | ${counts.map((n) => (n ? String(n) : "")).join(" | ")} |`);
  }
}
rows.push(`\n## Rust crates\n\n| crate | role | .rs files | ${RS_LIBS.join(" | ")} |\n|---|---|---|${RS_LIBS.map(() => "---").join("|")}|`);
for (const base of ["crates", "tools"]) {
  if (!existsSync(base)) continue;
  for (const c of readdirSync(base)) {
    const ct = join(base, c, "Cargo.toml");
    if (!existsSync(ct)) continue;
    const toml = readFileSync(ct, "utf8");
    const desc = (/^description\s*=\s*"([^"]*)"/m.exec(toml)?.[1] ?? "").replace(/\|/g, "/").slice(0, 70);
    const n = existsSync(join(base, c, "src")) ? files(join(base, c, "src"), /\.rs$/).length : 0;
    const has = RS_LIBS.map((l) => (new RegExp(`^${l.replace("-", "[-_]")}\\s*(=|\\.)`, "m").test(toml) ? "x" : ""));
    rows.push(`| ${base}/${c} | ${desc} | ${n} | ${has.join(" | ")} |`);
  }
}
// Internal dependency graph: which workspace imports which @rosegriffon/* package.
const edges: string[] = [];
for (const base of ["apps", "packages"]) for (const ws of readdirSync(base)) {
  const pj = join(base, ws, "package.json"); if (!existsSync(pj)) continue;
  const j = JSON.parse(readFileSync(pj, "utf8"));
  for (const d of Object.keys({ ...j.dependencies, ...j.devDependencies, ...j.peerDependencies }))
    if (d.startsWith("@rosegriffon/")) edges.push(`  "${j.name ?? ws}" --> "${d}"`);
}
rows.push(`\n## Internal package graph\n\n\`\`\`mermaid\nflowchart LR\n${[...new Set(edges)].join("\n")}\n\`\`\``);
console.log(`# Stack import matrix\n\nGenerated by \`bun docs/proofs/stack/matrix.ts\`. TS cells: number of files importing the library. Rust cells: declared dependency.\n\n${rows.join("\n")}`);
