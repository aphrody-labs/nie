//! One emitter per language. Every function is a pure `Contract -> String` map.

use std::fmt::Write as _;

use anyhow::bail;
use nie_abi::{Contract, Func, Ty};

/// A target language.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Lang {
    /// C header.
    C,
    /// C++20 header over the C header.
    Cpp,
    /// Rust `extern "C"` declarations and safe wrappers.
    Rust,
    /// Python, `ctypes`.
    Python,
    /// C#, P/Invoke.
    CSharp,
    /// Go, cgo.
    Go,
    /// TypeScript for `bun:ffi`.
    Bun,
    /// Zig.
    Zig,
}

impl Lang {
    /// Every language, in emission order.
    pub const ALL: [Self; 8] = [
        Self::C,
        Self::Cpp,
        Self::Rust,
        Self::Python,
        Self::CSharp,
        Self::Go,
        Self::Bun,
        Self::Zig,
    ];

    fn id(self) -> &'static str {
        match self {
            Self::C => "c",
            Self::Cpp => "cpp",
            Self::Rust => "rust",
            Self::Python => "python",
            Self::CSharp => "csharp",
            Self::Go => "go",
            Self::Bun => "bun",
            Self::Zig => "zig",
        }
    }

    /// Parses `--lang` values; an empty list selects every language.
    ///
    /// # Errors
    /// On an unknown language name.
    pub fn parse_list(names: &[String]) -> anyhow::Result<Vec<Self>> {
        if names.is_empty() {
            return Ok(Self::ALL.to_vec());
        }
        let mut out = Vec::new();
        for n in names {
            let Some(l) = Self::ALL.iter().find(|l| l.id() == n.as_str()) else {
                bail!(
                    "unknown language `{n}`; known: {}",
                    Self::ALL.map(Self::id).join(", ")
                );
            };
            out.push(*l);
        }
        out.sort();
        out.dedup();
        Ok(out)
    }
}

/// Every generated file as `(relative path, text)`, sorted by path.
#[must_use]
pub fn emit_all(c: &Contract, lib: &str, langs: &[Lang]) -> Vec<(String, String)> {
    let mut files = Vec::new();
    for lang in langs {
        let n = &c.name;
        match lang {
            Lang::C => files.push((format!("c/{n}.h"), nie_abi::emit_c_header(c))),
            Lang::Cpp => files.push((format!("cpp/{n}.hpp"), cpp(c, lib))),
            Lang::Rust => files.push((format!("rust/{n}_sys.rs"), rust(c))),
            Lang::Python => files.push((format!("python/{n}.py"), python(c, lib))),
            Lang::CSharp => files.push((format!("csharp/{}.cs", pascal(n)), csharp(c, lib))),
            Lang::Go => files.push((format!("go/{n}.go"), go(c, lib))),
            Lang::Bun => files.push((format!("bun/{n}.ts"), nie_abi::emit_ts(c))),
            Lang::Zig => files.push((format!("zig/{n}.zig"), zig(c, lib))),
        }
    }
    files.sort();
    files
}

const BANNER: &str = "GENERATED by nie bindgen from the C ABI contract. Do not edit.";

fn doc(f: &Func) -> String {
    f.doc.replace("*/", "* /").replace('\n', " ")
}

fn short(name: &str) -> &str {
    name.strip_prefix("nie_").unwrap_or(name)
}

fn pascal(name: &str) -> String {
    let mut out = String::new();
    let mut up = true;
    for ch in name.chars() {
        if ch == '_' {
            up = true;
        } else if up {
            out.extend(ch.to_uppercase());
            up = false;
        } else {
            out.push(ch);
        }
    }
    out
}

fn camel(name: &str) -> String {
    let p = pascal(name);
    let mut ch = p.chars();
    ch.next().map_or_else(String::new, |f| {
        f.to_lowercase().collect::<String>() + ch.as_str()
    })
}

// ---------------------------------------------------------------- C++

fn cpp_ty(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "double",
        Ty::U64 => "std::uint64_t",
        Ty::U32 => "std::uint32_t",
        Ty::I32 => "std::int32_t",
        Ty::Bool => "bool",
        Ty::Str => "const std::string &",
        Ty::Bytes => "std::span<const std::uint8_t>",
        Ty::String => "std::optional<std::string>",
    }
}

fn cpp(c: &Contract, lib: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "// {BANNER}");
    let _ = writeln!(s, "#pragma once\n");
    let _ = writeln!(s, "#include <cstdint>\n#include <optional>\n#include <span>\n#include <string>\n");
    let _ = writeln!(s, "#include \"../c/{}.h\"\n", c.name);
    let _ = writeln!(s, "namespace {lib} {{\n");
    let _ = writeln!(s, "/// ABI version of the loaded library.");
    let _ = writeln!(s, "inline std::uint32_t abi_version() {{ return nie_ffi_abi_version(); }}\n");
    for f in &c.functions {
        let params: Vec<String> = f
            .args
            .iter()
            .map(|a| format!("{} {}", cpp_ty(a.ty), a.name))
            .collect();
        let call: Vec<String> = f
            .args
            .iter()
            .map(|a| match a.ty {
                Ty::Str => format!("{}.c_str()", a.name),
                Ty::Bytes => format!("{0}.data(), {0}.size()", a.name),
                _ => a.name.clone(),
            })
            .collect();
        let _ = writeln!(s, "/// {}", doc(f));
        let _ = writeln!(
            s,
            "inline {} {}({}) {{",
            cpp_ty(f.returns),
            short(&f.name),
            params.join(", ")
        );
        if f.returns == Ty::String {
            let _ = writeln!(
                s,
                "    char *raw = {}({});\n    if (raw == nullptr) {{\n        return std::nullopt;\n    }}\n    std::string out(raw);\n    nie_string_free(raw);\n    return out;\n}}\n",
                f.name,
                call.join(", ")
            );
        } else {
            let _ = writeln!(s, "    return {}({});\n}}\n", f.name, call.join(", "));
        }
    }
    let _ = writeln!(s, "}}  // namespace {lib}");
    s
}

// ---------------------------------------------------------------- Rust

fn rust_raw(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "f64",
        Ty::U64 => "u64",
        Ty::U32 => "u32",
        Ty::I32 => "i32",
        Ty::Bool => "bool",
        Ty::Str => "*const c_char",
        Ty::Bytes => "*const u8",
        Ty::String => "*mut c_char",
    }
}

fn rust_safe(t: Ty) -> &'static str {
    match t {
        Ty::Str => "&CStr",
        Ty::Bytes => "&[u8]",
        Ty::String => "Option<String>",
        t => rust_raw(t),
    }
}

fn rust(c: &Contract) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "// {BANNER}");
    let _ = writeln!(s, "// Link the shared library of the contract; every function here is `unsafe`");
    let _ = writeln!(s, "// to call except the wrappers of the `safe` module.\n");
    let _ = writeln!(s, "use std::ffi::{{CStr, c_char}};\n");
    let _ = writeln!(s, "pub const ABI_VERSION: u32 = {};\n", c.abi_version);
    let _ = writeln!(s, "unsafe extern \"C\" {{");
    let _ = writeln!(s, "    pub fn nie_ffi_abi_version() -> u32;");
    let _ = writeln!(s, "    pub fn nie_string_free(s: *mut c_char);");
    for f in &c.functions {
        let mut params = Vec::new();
        for a in &f.args {
            params.push(format!("{}: {}", a.name, rust_raw(a.ty)));
            if a.ty == Ty::Bytes {
                params.push(format!("{}_len: usize", a.name));
            }
        }
        let _ = writeln!(s, "    /// {}", doc(f));
        let _ = writeln!(
            s,
            "    pub fn {}({}) -> {};",
            f.name,
            params.join(", "),
            rust_raw(f.returns)
        );
    }
    let _ = writeln!(s, "}}\n");
    let _ = writeln!(s, "/// Safe wrappers: strings are copied and freed, slices carry their length.");
    let _ = writeln!(s, "pub mod safe {{");
    let _ = writeln!(s, "    use super::*;\n");
    let _ = writeln!(s, "    /// ABI version of the loaded library.");
    let _ = writeln!(s, "    #[must_use]\n    pub fn abi_version() -> u32 {{\n        unsafe {{ nie_ffi_abi_version() }}\n    }}\n");
    for f in &c.functions {
        let params: Vec<String> = f
            .args
            .iter()
            .map(|a| format!("{}: {}", a.name, rust_safe(a.ty)))
            .collect();
        let call: Vec<String> = f
            .args
            .iter()
            .map(|a| match a.ty {
                Ty::Str => format!("{}.as_ptr()", a.name),
                Ty::Bytes => format!("{0}.as_ptr(), {0}.len()", a.name),
                _ => a.name.clone(),
            })
            .collect();
        let _ = writeln!(s, "    /// {}", doc(f));
        let _ = writeln!(
            s,
            "    pub fn {}({}) -> {} {{",
            short(&f.name),
            params.join(", "),
            rust_safe(f.returns)
        );
        if f.returns == Ty::String {
            let _ = writeln!(
                s,
                "        let raw = unsafe {{ {}({}) }};\n        if raw.is_null() {{\n            return None;\n        }}\n        let out = unsafe {{ CStr::from_ptr(raw) }}.to_string_lossy().into_owned();\n        unsafe {{ nie_string_free(raw) }};\n        Some(out)\n    }}\n",
                f.name,
                call.join(", ")
            );
        } else {
            let _ = writeln!(s, "        unsafe {{ {}({}) }}\n    }}\n", f.name, call.join(", "));
        }
    }
    let _ = writeln!(s, "}}");
    s
}

// ---------------------------------------------------------------- Python

fn py_c(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "ctypes.c_double",
        Ty::U64 => "ctypes.c_uint64",
        Ty::U32 => "ctypes.c_uint32",
        Ty::I32 => "ctypes.c_int32",
        Ty::Bool => "ctypes.c_bool",
        Ty::Str | Ty::Bytes => "ctypes.c_char_p",
        Ty::String => "ctypes.c_void_p",
    }
}

fn py_ty(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "float",
        Ty::U64 | Ty::U32 | Ty::I32 => "int",
        Ty::Bool => "bool",
        Ty::Str => "str",
        Ty::Bytes => "bytes",
        Ty::String => "str | None",
    }
}

fn python(c: &Contract, lib: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "\"\"\"{BANNER}\"\"\"");
    let _ = writeln!(s, "from __future__ import annotations\n");
    let _ = writeln!(s, "import ctypes\nimport ctypes.util\nimport os\nimport sys\n");
    let _ = writeln!(s, "ABI_VERSION = {}", c.abi_version);
    let _ = writeln!(s, "LIBRARY = \"{lib}\"\n\n");
    let _ = writeln!(s, "def _candidates(path: str | None) -> list[str]:");
    let _ = writeln!(s, "    if path:\n        return [path]");
    let _ = writeln!(s, "    env = os.environ.get(\"{}_LIB\")", lib.to_uppercase());
    let _ = writeln!(s, "    if env:\n        return [env]");
    let _ = writeln!(s, "    if sys.platform == \"win32\":\n        names = [LIBRARY + \".dll\"]");
    let _ = writeln!(s, "    elif sys.platform == \"darwin\":\n        names = [\"lib\" + LIBRARY + \".dylib\"]");
    let _ = writeln!(s, "    else:\n        names = [\"lib\" + LIBRARY + \".so\"]");
    let _ = writeln!(s, "    found = ctypes.util.find_library(LIBRARY)");
    let _ = writeln!(s, "    return names + ([found] if found else [])\n\n");
    let _ = writeln!(s, "class Library:");
    let _ = writeln!(s, "    \"\"\"The loaded shared library and its typed functions.\"\"\"\n");
    let _ = writeln!(s, "    def __init__(self, path: str | None = None) -> None:");
    let _ = writeln!(s, "        last: OSError | None = None");
    let _ = writeln!(s, "        for candidate in _candidates(path):");
    let _ = writeln!(s, "            try:\n                self._lib = ctypes.CDLL(candidate)\n                break\n            except OSError as err:\n                last = err");
    let _ = writeln!(s, "        else:\n            raise OSError(f\"cannot load {{LIBRARY}}: {{last}}\")");
    let _ = writeln!(s, "        self._lib.nie_ffi_abi_version.restype = ctypes.c_uint32");
    let _ = writeln!(s, "        self._lib.nie_ffi_abi_version.argtypes = []");
    let _ = writeln!(s, "        self._lib.nie_string_free.restype = None");
    let _ = writeln!(s, "        self._lib.nie_string_free.argtypes = [ctypes.c_void_p]");
    for f in &c.functions {
        let mut types = Vec::new();
        for a in &f.args {
            types.push(py_c(a.ty));
            if a.ty == Ty::Bytes {
                types.push("ctypes.c_size_t");
            }
        }
        let _ = writeln!(s, "        self._lib.{}.restype = {}", f.name, py_c(f.returns));
        let _ = writeln!(s, "        self._lib.{}.argtypes = [{}]", f.name, types.join(", "));
    }
    let _ = writeln!(s, "        if self.abi_version() != ABI_VERSION:");
    let _ = writeln!(s, "            raise RuntimeError(f\"ABI mismatch: library {{self.abi_version()}}, binding {{ABI_VERSION}}\")\n");
    let _ = writeln!(s, "    def abi_version(self) -> int:");
    let _ = writeln!(s, "        \"\"\"ABI version of the loaded library.\"\"\"");
    let _ = writeln!(s, "        return int(self._lib.nie_ffi_abi_version())\n");
    for f in &c.functions {
        let mut params = vec!["self".to_owned()];
        params.extend(f.args.iter().map(|a| format!("{}: {}", a.name, py_ty(a.ty))));
        let mut call = Vec::new();
        for a in &f.args {
            match a.ty {
                Ty::Str => call.push(format!("{}.encode(\"utf-8\")", a.name)),
                Ty::Bytes => {
                    call.push(a.name.clone());
                    call.push(format!("len({})", a.name));
                }
                _ => call.push(a.name.clone()),
            }
        }
        let _ = writeln!(s, "    def {}({}) -> {}:", short(&f.name), params.join(", "), py_ty(f.returns));
        let _ = writeln!(s, "        \"\"\"{}\"\"\"", doc(f).replace('"', "'"));
        if f.returns == Ty::String {
            let _ = writeln!(s, "        raw = self._lib.{}({})", f.name, call.join(", "));
            let _ = writeln!(s, "        if not raw:\n            return None");
            let _ = writeln!(s, "        try:\n            return ctypes.string_at(raw).decode(\"utf-8\")");
            let _ = writeln!(s, "        finally:\n            self._lib.nie_string_free(raw)\n");
        } else {
            let _ = writeln!(s, "        return self._lib.{}({})\n", f.name, call.join(", "));
        }
    }
    s
}

// ---------------------------------------------------------------- C#

fn cs_native(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "double",
        Ty::U64 => "ulong",
        Ty::U32 => "uint",
        Ty::I32 => "int",
        Ty::Bool => "[MarshalAs(UnmanagedType.U1)] bool",
        Ty::Str => "[MarshalAs(UnmanagedType.LPUTF8Str)] string",
        Ty::Bytes => "byte[]",
        Ty::String => "IntPtr",
    }
}

fn cs_ty(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "double",
        Ty::U64 => "ulong",
        Ty::U32 => "uint",
        Ty::I32 => "int",
        Ty::Bool => "bool",
        Ty::Str => "string",
        Ty::Bytes => "byte[]",
        Ty::String => "string?",
    }
}

fn csharp(c: &Contract, lib: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "// {BANNER}");
    let _ = writeln!(s, "#nullable enable\nusing System;\nusing System.Reflection;\nusing System.Runtime.InteropServices;\n");
    let _ = writeln!(s, "namespace {};\n", pascal(lib));
    let _ = writeln!(s, "/// <summary>Raw P/Invoke declarations.</summary>");
    let _ = writeln!(s, "internal static class Native");
    let _ = writeln!(s, "{{");
    let _ = writeln!(s, "    internal const string Lib = \"{lib}\";\n");
    let _ = writeln!(s, "    static Native()");
    let _ = writeln!(s, "    {{");
    let _ = writeln!(
        s,
        "        NativeLibrary.SetDllImportResolver(typeof(Native).Assembly, (name, assembly, path) =>\n        {{\n            var env = Environment.GetEnvironmentVariable(\"{}_LIB\");\n            return name == Lib && !string.IsNullOrEmpty(env) ? NativeLibrary.Load(env) : IntPtr.Zero;\n        }});",
        lib.to_uppercase()
    );
    let _ = writeln!(s, "    }}\n");
    let _ = writeln!(s, "    [DllImport(Lib, CallingConvention = CallingConvention.Cdecl)]");
    let _ = writeln!(s, "    internal static extern uint nie_ffi_abi_version();\n");
    let _ = writeln!(s, "    [DllImport(Lib, CallingConvention = CallingConvention.Cdecl)]");
    let _ = writeln!(s, "    internal static extern void nie_string_free(IntPtr s);\n");
    for f in &c.functions {
        let mut params = Vec::new();
        for a in &f.args {
            params.push(format!("{} {}", cs_native(a.ty), a.name));
            if a.ty == Ty::Bytes {
                params.push(format!("UIntPtr {}_len", a.name));
            }
        }
        let _ = writeln!(s, "    [DllImport(Lib, CallingConvention = CallingConvention.Cdecl)]");
        let ret = if f.returns == Ty::Bool {
            "[return: MarshalAs(UnmanagedType.U1)] bool"
        } else {
            cs_native(f.returns)
        };
        let _ = writeln!(s, "    internal static extern {ret} {}({});\n", f.name, params.join(", "));
    }
    let _ = writeln!(s, "}}\n");
    let _ = writeln!(s, "/// <summary>Typed API: strings are copied and freed.</summary>");
    let _ = writeln!(s, "public static class Api");
    let _ = writeln!(s, "{{");
    let _ = writeln!(s, "    public const uint AbiVersionExpected = {}u;\n", c.abi_version);
    let _ = writeln!(s, "    /// <summary>ABI version of the loaded library.</summary>");
    let _ = writeln!(s, "    public static uint AbiVersion() => Native.nie_ffi_abi_version();\n");
    for f in &c.functions {
        let params: Vec<String> = f
            .args
            .iter()
            .map(|a| format!("{} {}", cs_ty(a.ty), camel(&a.name)))
            .collect();
        let mut call = Vec::new();
        for a in &f.args {
            match a.ty {
                Ty::Bytes => {
                    call.push(camel(&a.name));
                    call.push(format!("(UIntPtr){}.Length", camel(&a.name)));
                }
                _ => call.push(camel(&a.name)),
            }
        }
        let _ = writeln!(s, "    /// <summary>{}</summary>", doc(f).replace('<', "&lt;").replace('>', "&gt;"));
        if f.returns == Ty::String {
            let _ = writeln!(s, "    public static string? {}({})", pascal(short(&f.name)), params.join(", "));
            let _ = writeln!(s, "    {{");
            let _ = writeln!(s, "        var raw = Native.{}({});", f.name, call.join(", "));
            let _ = writeln!(s, "        if (raw == IntPtr.Zero) return null;");
            let _ = writeln!(s, "        try {{ return Marshal.PtrToStringUTF8(raw); }}");
            let _ = writeln!(s, "        finally {{ Native.nie_string_free(raw); }}");
            let _ = writeln!(s, "    }}\n");
        } else {
            let _ = writeln!(
                s,
                "    public static {} {}({}) => Native.{}({});\n",
                cs_ty(f.returns),
                pascal(short(&f.name)),
                params.join(", "),
                f.name,
                call.join(", ")
            );
        }
    }
    let _ = writeln!(s, "}}");
    s
}

// ---------------------------------------------------------------- Go

fn go_ty(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "float64",
        Ty::U64 => "uint64",
        Ty::U32 => "uint32",
        Ty::I32 => "int32",
        Ty::Bool => "bool",
        Ty::Str => "string",
        Ty::Bytes => "[]byte",
        Ty::String => "(string, bool)",
    }
}

fn go_cast(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "C.double",
        Ty::U64 => "C.uint64_t",
        Ty::U32 => "C.uint32_t",
        Ty::I32 => "C.int32_t",
        Ty::Bool => "C.bool",
        _ => "",
    }
}

fn go(c: &Contract, lib: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "// {BANNER}\n");
    let _ = writeln!(s, "package {lib}\n");
    let _ = writeln!(s, "/*");
    let _ = writeln!(s, "#cgo CFLAGS: -I${{SRCDIR}}/../c");
    let _ = writeln!(s, "#cgo LDFLAGS: -l{lib}");
    let _ = writeln!(s, "#include <stdlib.h>");
    let _ = writeln!(s, "#include \"{}.h\"", c.name);
    let _ = writeln!(s, "*/");
    let _ = writeln!(s, "import \"C\"\n");
    let _ = writeln!(s, "import \"unsafe\"\n");
    let _ = writeln!(s, "// AbiVersionExpected is the ABI version this binding was generated for.");
    let _ = writeln!(s, "const AbiVersionExpected uint32 = {}\n", c.abi_version);
    let _ = writeln!(s, "// AbiVersion returns the ABI version of the loaded library.");
    let _ = writeln!(s, "func AbiVersion() uint32 {{ return uint32(C.nie_ffi_abi_version()) }}\n");
    for f in &c.functions {
        let params: Vec<String> = f
            .args
            .iter()
            .map(|a| format!("{} {}", camel(&a.name), go_ty(a.ty)))
            .collect();
        let _ = writeln!(s, "// {} {}", pascal(short(&f.name)), doc(f));
        let ret = go_ty(f.returns);
        let _ = writeln!(s, "func {}({}) {} {{", pascal(short(&f.name)), params.join(", "), ret);
        let mut call = Vec::new();
        for a in &f.args {
            let n = camel(&a.name);
            match a.ty {
                Ty::Str => {
                    let _ = writeln!(s, "\tc_{n} := C.CString({n})\n\tdefer C.free(unsafe.Pointer(c_{n}))");
                    call.push(format!("c_{n}"));
                }
                Ty::Bytes => {
                    let _ = writeln!(s, "\tvar p_{n} *C.uint8_t\n\tif len({n}) > 0 {{\n\t\tp_{n} = (*C.uint8_t)(unsafe.Pointer(&{n}[0]))\n\t}}");
                    call.push(format!("p_{n}"));
                    call.push(format!("C.size_t(len({n}))"));
                }
                t => call.push(format!("{}({n})", go_cast(t))),
            }
        }
        let invoke = format!("C.{}({})", f.name, call.join(", "));
        match f.returns {
            Ty::String => {
                let _ = writeln!(s, "\traw := {invoke}\n\tif raw == nil {{\n\t\treturn \"\", false\n\t}}\n\tout := C.GoString(raw)\n\tC.nie_string_free(raw)\n\treturn out, true\n}}\n");
            }
            Ty::Bool => {
                let _ = writeln!(s, "\treturn bool({invoke})\n}}\n");
            }
            t => {
                let _ = writeln!(s, "\treturn {}({invoke})\n}}\n", go_ty(t));
            }
        }
    }
    s
}

