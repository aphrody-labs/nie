//! The per-crate C ABI ("crlib"): every library crate of the workspace that has a C surface lists
//! its functions in `<crate>/abi.json`, and `crates/nie-abi/crlib.json` lists every workspace
//! member with its status (`crlib`, or `excluded` with the reason). From these files the
//! generator writes `include/nie_<id>.h` and `<crate>/src/abi_generated.rs`, and a test fails
//! when a committed file drifts or a workspace member is missing from the manifest.
//!
//! Every crlib exports three base symbols next to its own functions: `nie_<id>_abi_version`,
//! `nie_<id>_info` (a JSON description of the crate) and `nie_<id>_string_free`.

use serde::Deserialize;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::{Func, Ty, c_args, c_ret, rust_fn};

/// Manifest source.
pub const MANIFEST_JSON: &str = include_str!("../crlib.json");

/// How a workspace member takes part in the crlib scheme.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Status {
    /// Builds as `rlib`, `staticlib` and `cdylib` with the `crlib` feature.
    Crlib,
    /// Not a C-ABI library; the reason says why.
    Excluded,
}

/// Where the C surface of a crlib comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Surface {
    /// `<crate>/abi.json`, generated by this crate.
    #[default]
    Generated,
    /// A contract generated by its own generator (`nie-ffi`, see `contract.json`).
    Contract,
}

/// One workspace member.
#[derive(Debug, Clone, Deserialize)]
pub struct Entry {
    /// Cargo package name.
    pub package: String,
    /// Directory relative to the workspace root.
    pub path: String,
    /// Symbol and header id (`formats` gives `nie_formats_*` and `include/nie_formats.h`).
    #[serde(default)]
    pub id: String,
    /// Status.
    pub status: Status,
    /// Source of the C surface.
    #[serde(default)]
    pub surface: Surface,
    /// Why a member is excluded.
    #[serde(default)]
    pub reason: String,
}

/// The manifest.
#[derive(Debug, Clone, Deserialize)]
pub struct Manifest {
    /// Every workspace member.
    pub crates: Vec<Entry>,
}

/// The C surface of one crate.
#[derive(Debug, Clone, Deserialize)]
pub struct CrateAbi {
    /// Cargo package name.
    #[serde(rename = "crate")]
    pub package: String,
    /// Symbol and header id.
    pub id: String,
    /// Incremented on any ABI break of this crate.
    pub abi_version: u32,
    /// Exported functions; they are implemented in the crate's `abi_impls` module.
    #[serde(default)]
    pub functions: Vec<Func>,
}

/// Parses the manifest.
///
/// # Panics
/// On malformed JSON, a duplicated package, a crlib without id, or an exclusion without reason.
#[must_use]
pub fn load_manifest(text: &str) -> Manifest {
    let manifest: Manifest = serde_json::from_str(text).expect("crlib.json");
    let mut seen = std::collections::BTreeSet::new();
    let mut ids = std::collections::BTreeSet::new();
    for e in &manifest.crates {
        assert!(
            seen.insert(e.package.as_str()),
            "{} listed twice",
            e.package
        );
        match e.status {
            Status::Crlib => {
                assert!(!e.id.is_empty(), "{}: a crlib needs an id", e.package);
                assert!(ids.insert(e.id.as_str()), "id {} used twice", e.id);
            }
            Status::Excluded => {
                assert!(
                    !e.reason.trim().is_empty(),
                    "{}: an exclusion needs a reason",
                    e.package
                );
            }
        }
    }
    manifest
}

/// Parses and validates the `abi.json` of one crate.
///
/// # Panics
/// On malformed JSON or a symbol outside `nie_<id>_`.
#[must_use]
pub fn load_abi(text: &str, entry: &Entry) -> CrateAbi {
    let abi: CrateAbi = serde_json::from_str(text).expect("abi.json");
    assert_eq!(abi.package, entry.package, "abi.json names another crate");
    assert_eq!(abi.id, entry.id, "abi.json id differs from the manifest");
    let prefix = format!("nie_{}_", abi.id);
    let reserved = [
        format!("{prefix}abi_version"),
        format!("{prefix}info"),
        format!("{prefix}string_free"),
    ];
    let mut seen = std::collections::BTreeSet::new();
    for f in &abi.functions {
        assert!(
            f.name.starts_with(&prefix),
            "{}: symbols of {} start with {prefix}",
            f.name,
            abi.package
        );
        assert!(!reserved.contains(&f.name), "{} is a base symbol", f.name);
        assert!(seen.insert(f.name.clone()), "duplicate symbol {}", f.name);
        assert!(
            f.args.iter().all(|a| a.ty != Ty::String),
            "{}: string is output only",
            f.name
        );
        assert!(
            !matches!(f.returns, Ty::Str | Ty::Bytes),
            "{}: return a `string`",
            f.name
        );
    }
    abi
}

/// The C header of a crate, `include/nie_<id>.h`.
#[must_use]
pub fn emit_header(abi: &CrateAbi) -> String {
    let id = &abi.id;
    let upper = id.to_uppercase();
    let guard = format!("NIE_{upper}_H");
    let mut s = String::new();
    let _ = writeln!(
        s,
        "/* GENERATED by nie-abi-gen from the abi.json of {}. Do not edit. */",
        abi.package
    );
    let _ = writeln!(s, "#ifndef {guard}\n#define {guard}\n");
    let _ = writeln!(
        s,
        "#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n"
    );
    let _ = writeln!(s, "#ifdef __cplusplus\nextern \"C\" {{\n#endif\n");
    let _ = writeln!(
        s,
        "/* C ABI of the {} crate (build with --features crlib). */",
        abi.package
    );
    let _ = writeln!(s, "#define NIE_{upper}_ABI_VERSION {}u\n", abi.abi_version);
    let _ = writeln!(
        s,
        "/* ABI version of the loaded library; compare with NIE_{upper}_ABI_VERSION. */"
    );
    let _ = writeln!(s, "uint32_t nie_{id}_abi_version(void);\n");
    let _ = writeln!(
        s,
        "/* JSON description of the crate: name, version, ABI version and exported symbols.\n   Free the result with nie_{id}_string_free. */"
    );
    let _ = writeln!(s, "char *nie_{id}_info(void);\n");
    let _ = writeln!(
        s,
        "/* Frees a string returned by this library. NULL is accepted. */"
    );
    let _ = writeln!(s, "void nie_{id}_string_free(char *s);\n");
    for f in &abi.functions {
        let _ = writeln!(s, "/* {} */", f.doc);
        let _ = writeln!(s, "{} {}({});\n", c_ret(f.returns), f.name, c_args(f));
    }
    let _ = writeln!(s, "#ifdef __cplusplus\n}}\n#endif\n\n#endif /* {guard} */");
    s
}

/// The Rust `extern "C"` layer of a crate, `src/abi_generated.rs`.
#[must_use]
pub fn emit_rust(abi: &CrateAbi) -> String {
    let id = &abi.id;
    let mut symbols = vec![
        format!("nie_{id}_abi_version"),
        format!("nie_{id}_info"),
        format!("nie_{id}_string_free"),
    ];
    symbols.extend(abi.functions.iter().map(|f| f.name.clone()));
    let list = symbols
        .iter()
        .map(|n| format!("\\\"{n}\\\""))
        .collect::<Vec<_>>()
        .join(",");
    let mut s = String::new();
    let _ = writeln!(
        s,
        "// GENERATED by nie-abi-gen from the abi.json of {}. Do not edit.\n",
        abi.package
    );
    let _ = writeln!(s, "extern crate std;\n");
    let _ = writeln!(s, "use std::ffi::{{CStr, CString, c_char}};");
    let _ = writeln!(s, "use std::panic::{{AssertUnwindSafe, catch_unwind}};\n");
    let _ = writeln!(s, "/// ABI version of this library.");
    let _ = writeln!(
        s,
        "#[unsafe(no_mangle)]\npub extern \"C\" fn nie_{id}_abi_version() -> u32 {{\n    {}\n}}\n",
        abi.abi_version
    );
    let _ = writeln!(
        s,
        "/// JSON description of the crate: name, version, ABI version and exported symbols.\n#[unsafe(no_mangle)]\npub extern \"C\" fn nie_{id}_info() -> *mut c_char {{\n    const INFO: &str = concat!(\n        \"{{\\\"crate\\\":\\\"\",\n        env!(\"CARGO_PKG_NAME\"),\n        \"\\\",\\\"version\\\":\\\"\",\n        env!(\"CARGO_PKG_VERSION\"),\n        \"\\\",\\\"abi\\\":{},\\\"symbols\\\":[{list}]}}\"\n    );\n    CString::new(INFO).map_or(std::ptr::null_mut(), CString::into_raw)\n}}\n",
        abi.abi_version
    );
    let _ = writeln!(
        s,
        "/// Frees a string returned by this library.\n///\n/// # Safety\n/// `s` must be NULL or a pointer returned by this library and not freed yet.\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn nie_{id}_string_free(s: *mut c_char) {{\n    if !s.is_null() {{\n        drop(unsafe {{ CString::from_raw(s) }});\n    }}\n}}\n"
    );
    for f in &abi.functions {
        s.push_str(&rust_fn(f, "crate::abi_impls"));
    }
    s
}

/// Header path of a crlib relative to the workspace root.
#[must_use]
pub fn header_path(id: &str) -> PathBuf {
    PathBuf::from("include").join(format!("nie_{id}.h"))
}

/// Generated Rust path of a crlib relative to the workspace root.
#[must_use]
pub fn rust_path(entry: &Entry) -> PathBuf {
    PathBuf::from(&entry.path).join("src/abi_generated.rs")
}

/// Every generated file of the manifest as `(path relative to the root, content)`.
///
/// # Errors
/// When a crate's `abi.json` cannot be read.
pub fn generated_files(
    root: &Path,
    manifest: &Manifest,
) -> std::io::Result<Vec<(PathBuf, String)>> {
    let mut files = Vec::new();
    for e in manifest
        .crates
        .iter()
        .filter(|e| e.status == Status::Crlib && e.surface == Surface::Generated)
    {
        let path = root.join(&e.path).join("abi.json");
        let text = std::fs::read_to_string(&path)
            .map_err(|err| std::io::Error::new(err.kind(), format!("{}: {err}", path.display())))?;
        let abi = load_abi(&text, e);
        files.push((header_path(&e.id), emit_header(&abi)));
        files.push((rust_path(e), emit_rust(&abi)));
    }
    Ok(files)
}
