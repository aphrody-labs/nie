//! The contract is `contract.json`. Everything on both sides of the FFI is generated from it:
//! the C header, the Rust `extern "C"` layer, the `bun:ffi` binding and the OpenAPI document.

use serde::Deserialize;
use std::fmt::Write as _;

/// Contract source.
pub const CONTRACT_JSON: &str = include_str!("../contract.json");

/// A type usable across the FFI boundary.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
pub enum Ty {
    /// 64-bit float.
    #[serde(rename = "f64")]
    F64,
    /// Unsigned 64-bit.
    #[serde(rename = "u64")]
    U64,
    /// Unsigned 32-bit.
    #[serde(rename = "u32")]
    U32,
    /// Signed 32-bit.
    #[serde(rename = "i32")]
    I32,
    /// Boolean.
    #[serde(rename = "bool")]
    Bool,
    /// Input: NUL-terminated UTF-8 string. Output: owned `char*`, freed with `rg_string_free`.
    #[serde(rename = "str")]
    Str,
    /// Output string (owned), NULL on failure.
    #[serde(rename = "string")]
    String,
    /// Input: pointer and length.
    #[serde(rename = "bytes")]
    Bytes,
}

/// A function argument.
#[derive(Debug, Clone, Deserialize)]
pub struct Arg {
    /// Name.
    pub name: String,
    /// Type.
    #[serde(rename = "type")]
    pub ty: Ty,
}

/// An exported function.
#[derive(Debug, Clone, Deserialize)]
pub struct Func {
    /// C symbol (`rg_` prefix).
    pub name: String,
    /// Documentation.
    pub doc: String,
    /// Arguments.
    pub args: Vec<Arg>,
    /// Return type.
    pub returns: Ty,
}

/// The whole contract.
#[derive(Debug, Clone, Deserialize)]
pub struct Contract {
    /// Library name.
    pub name: String,
    /// Title.
    pub title: String,
    /// Semantic version of the contract.
    pub version: String,
    /// Incremented on any ABI break; returned by `rg_ffi_abi_version`.
    pub abi_version: u32,
    /// Functions.
    pub functions: Vec<Func>,
}

/// Loads and validates the contract.
///
/// # Panics
/// On a malformed contract (this is a build-time tool).
#[must_use]
pub fn load() -> Contract {
    let c: Contract = serde_json::from_str(CONTRACT_JSON).expect("contract.json");
    let mut seen = std::collections::BTreeSet::new();
    for f in &c.functions {
        assert!(f.name.starts_with("rg_"), "symbol {} must start with rg_", f.name);
        assert!(seen.insert(f.name.clone()), "duplicate symbol {}", f.name);
        assert!(f.args.iter().all(|a| a.ty != Ty::String), "{}: string is output only", f.name);
        assert!(!matches!(f.returns, Ty::Str | Ty::Bytes), "{}: return a `string`", f.name);
    }
    c
}

fn c_args(f: &Func) -> String {
    let mut parts = Vec::new();
    for a in &f.args {
        match a.ty {
            Ty::F64 => parts.push(format!("double {}", a.name)),
            Ty::U64 => parts.push(format!("uint64_t {}", a.name)),
            Ty::U32 => parts.push(format!("uint32_t {}", a.name)),
            Ty::I32 => parts.push(format!("int32_t {}", a.name)),
            Ty::Bool => parts.push(format!("bool {}", a.name)),
            Ty::Str => parts.push(format!("const char *{}", a.name)),
            Ty::Bytes => {
                parts.push(format!("const uint8_t *{}", a.name));
                parts.push(format!("size_t {}_len", a.name));
            }
            Ty::String => unreachable!("validated"),
        }
    }
    if parts.is_empty() { "void".into() } else { parts.join(", ") }
}

fn c_ret(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "double",
        Ty::U64 => "uint64_t",
        Ty::U32 => "uint32_t",
        Ty::I32 => "int32_t",
        Ty::Bool => "bool",
        Ty::String => "char *",
        Ty::Str | Ty::Bytes => unreachable!("validated"),
    }
}

/// C header.
#[must_use]
pub fn emit_c_header(c: &Contract) -> String {
    let guard = format!("{}_H", c.name.to_uppercase());
    let mut s = String::new();
    let _ = writeln!(s, "/* GENERATED by rg-ffi-gen from crates/rg-ffi-contract/contract.json. Do not edit. */");
    let _ = writeln!(s, "#ifndef {guard}\n#define {guard}\n");
    let _ = writeln!(s, "#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n");
    let _ = writeln!(s, "#ifdef __cplusplus\nextern \"C\" {{\n#endif\n");
    let _ = writeln!(s, "/* {} {} */", c.title, c.version);
    let _ = writeln!(s, "#define RG_FFI_ABI_VERSION {}u\n", c.abi_version);
    let _ = writeln!(s, "/* ABI version of the loaded library; compare with RG_FFI_ABI_VERSION. */");
    let _ = writeln!(s, "uint32_t rg_ffi_abi_version(void);\n");
    let _ = writeln!(s, "/* Frees a string returned by this library. NULL is accepted. */");
    let _ = writeln!(s, "void rg_string_free(char *s);\n");
    for f in &c.functions {
        let _ = writeln!(s, "/* {} */", f.doc);
        let _ = writeln!(s, "{} {}({});\n", c_ret(f.returns), f.name, c_args(f));
    }
    let _ = writeln!(s, "#ifdef __cplusplus\n}}\n#endif\n\n#endif /* {guard} */");
    s
}

fn rust_ty(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "f64",
        Ty::U64 => "u64",
        Ty::U32 => "u32",
        Ty::I32 => "i32",
        Ty::Bool => "bool",
        Ty::String => "*mut c_char",
        Ty::Str | Ty::Bytes => unreachable!("validated"),
    }
}

/// Rust `extern "C"` layer. It calls `crate::impls::<symbol>` with safe Rust types.
#[must_use]
pub fn emit_rust(c: &Contract) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "// GENERATED by rg-ffi-gen from crates/rg-ffi-contract/contract.json. Do not edit.\n");
    let _ = writeln!(s, "use std::ffi::{{CStr, CString, c_char}};");
    let _ = writeln!(s, "use std::panic::{{AssertUnwindSafe, catch_unwind}};\n");
    let _ = writeln!(s, "/// ABI version of this library.");
    let _ = writeln!(s, "#[unsafe(no_mangle)]\npub extern \"C\" fn rg_ffi_abi_version() -> u32 {{\n    {}\n}}\n", c.abi_version);
    let _ = writeln!(s, "/// Frees a string returned by this library.\n///\n/// # Safety\n/// `s` must be NULL or a pointer returned by this library and not freed yet.");
    let _ = writeln!(s, "#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn rg_string_free(s: *mut c_char) {{\n    if !s.is_null() {{\n        drop(unsafe {{ CString::from_raw(s) }});\n    }}\n}}\n");
    for f in &c.functions {
        let _ = writeln!(s, "/// {}\n///\n/// # Safety\n/// Pointer arguments must be valid for the stated lengths (strings NUL-terminated).", f.doc);
        let mut params = Vec::new();
        for a in &f.args {
            match a.ty {
                Ty::Str => params.push(format!("{}: *const c_char", a.name)),
                Ty::Bytes => {
                    params.push(format!("{}: *const u8", a.name));
                    params.push(format!("{}_len: usize", a.name));
                }
                t => params.push(format!("{}: {}", a.name, rust_ty(t))),
            }
        }
        let fail = match f.returns {
            Ty::F64 => "f64::NAN",
            Ty::U64 | Ty::U32 | Ty::I32 => "0",
            Ty::Bool => "false",
            Ty::String => "std::ptr::null_mut()",
            Ty::Str | Ty::Bytes => unreachable!("validated"),
        };
        let _ = writeln!(s, "#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {}({}) -> {} {{", f.name, params.join(", "), rust_ty(f.returns));
        let mut call_args = Vec::new();
        for a in &f.args {
            match a.ty {
                Ty::Str => {
                    let _ = writeln!(s, "    if {0}.is_null() {{\n        return {fail};\n    }}\n    let Ok({0}) = unsafe {{ CStr::from_ptr({0}) }}.to_str() else {{\n        return {fail};\n    }};", a.name);
                    call_args.push(a.name.clone());
                }
                Ty::Bytes => {
                    let _ = writeln!(s, "    let {0}: &[u8] = if {0}.is_null() {{\n        &[]\n    }} else {{\n        unsafe {{ std::slice::from_raw_parts({0}, {0}_len) }}\n    }};", a.name);
                    call_args.push(a.name.clone());
                }
                _ => call_args.push(a.name.clone()),
            }
        }
        let call = format!("crate::impls::{}({})", f.name, call_args.join(", "));
        if f.returns == Ty::String {
            let _ = writeln!(s, "    catch_unwind(AssertUnwindSafe(|| match {call} {{\n        Some(out) => CString::new(out).map_or(std::ptr::null_mut(), CString::into_raw),\n        None => std::ptr::null_mut(),\n    }}))\n    .unwrap_or({fail})\n}}\n");
        } else {
            let _ = writeln!(s, "    catch_unwind(AssertUnwindSafe(|| {call})).unwrap_or({fail})\n}}\n");
        }
    }
    s
}

fn ffi_type(t: Ty) -> &'static str {
    match t {
        Ty::F64 => "FFIType.f64",
        Ty::U64 => "FFIType.u64_fast",
        Ty::U32 => "FFIType.u32",
        Ty::I32 => "FFIType.i32",
        Ty::Bool => "FFIType.bool",
        Ty::Str | Ty::Bytes | Ty::String => "FFIType.ptr",
    }
}

fn ts_ty(t: Ty) -> &'static str {
    match t {
        Ty::F64 | Ty::U64 | Ty::U32 | Ty::I32 => "number",
        Ty::Bool => "boolean",
        Ty::Str => "string",
        Ty::Bytes => "Uint8Array",
        Ty::String => "string | null",
    }
}

fn camel(name: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for ch in name.trim_start_matches("rg_").chars() {
        if ch == '_' {
            up = true;
        } else if up {
            out.extend(ch.to_uppercase());
            up = false;
        } else {
            out.push(ch);
        }
    }
    out
}

/// `bun:ffi` binding.
#[must_use]
pub fn emit_ts(c: &Contract) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "// GENERATED by rg-ffi-gen from crates/rg-ffi-contract/contract.json. Do not edit.");
    let _ = writeln!(s, "import {{ CString, FFIType, dlopen, ptr }} from \"bun:ffi\";\n");
    let _ = writeln!(s, "export const RG_FFI_ABI_VERSION = {};\n", c.abi_version);
    let _ = writeln!(s, "const encoder = new TextEncoder();");
    let _ = writeln!(s, "const cstr = (value: string): Uint8Array => encoder.encode(`${{value}}\\0`);\n");
    let _ = writeln!(s, "/** Opens the shared library built from the `rg-ffi` crate and returns the typed API. */");
    let _ = writeln!(s, "export function openRgFfi(libraryPath: string) {{");
    let _ = writeln!(s, "  const lib = dlopen(libraryPath, {{");
    let _ = writeln!(s, "    rg_ffi_abi_version: {{ args: [], returns: FFIType.u32 }},");
    let _ = writeln!(s, "    rg_string_free: {{ args: [FFIType.ptr], returns: FFIType.void }},");
    for f in &c.functions {
        let mut args = Vec::new();
        for a in &f.args {
            args.push(ffi_type(a.ty).to_owned());
            if a.ty == Ty::Bytes {
                args.push("FFIType.u64_fast".into());
            }
        }
        let _ = writeln!(s, "    {}: {{ args: [{}], returns: {} }},", f.name, args.join(", "), ffi_type(f.returns));
    }
    let _ = writeln!(s, "  }});\n  const sym = lib.symbols;");
    let _ = writeln!(s, "  const takeString = (p: number | null): string | null => {{");
    let _ = writeln!(s, "    if (p === null || p === 0) return null;");
    let _ = writeln!(s, "    const text = new CString(p as never).toString();");
    let _ = writeln!(s, "    sym.rg_string_free(p as never);\n    return text;\n  }};");
    let _ = writeln!(s, "  if (sym.rg_ffi_abi_version() !== RG_FFI_ABI_VERSION) {{");
    let _ = writeln!(s, "    throw new Error(`rg-ffi ABI mismatch: library ${{sym.rg_ffi_abi_version()}}, binding {}`);", c.abi_version);
    let _ = writeln!(s, "  }}\n  return {{\n    close: () => lib.close(),");
    for f in &c.functions {
        let params: Vec<String> = f.args.iter().map(|a| format!("{}: {}", camel(&a.name), ts_ty(a.ty))).collect();
        let mut call = Vec::new();
        for a in &f.args {
            let n = camel(&a.name);
            match a.ty {
                Ty::Str => call.push(format!("ptr(cstr({n}))")),
                Ty::Bytes => {
                    call.push(format!("ptr({n})"));
                    call.push(format!("{n}.length"));
                }
                _ => call.push(n),
            }
        }
        let invoke = format!("sym.{}({})", f.name, call.join(", "));
        let body = if f.returns == Ty::String { format!("takeString({invoke} as number | null)") } else { invoke };
        let _ = writeln!(s, "    /** {} */\n    {}: ({}): {} => {},", f.doc, camel(&f.name), params.join(", "), ts_ty(f.returns), body);
    }
    let _ = writeln!(s, "  }};\n}}\n\nexport type RgFfi = ReturnType<typeof openRgFfi>;");
    s
}

fn json_schema(t: Ty) -> serde_json::Value {
    use serde_json::json;
    match t {
        Ty::F64 => json!({"type": "number"}),
        Ty::U64 | Ty::U32 => json!({"type": "integer", "minimum": 0}),
        Ty::I32 => json!({"type": "integer"}),
        Ty::Bool => json!({"type": "boolean"}),
        Ty::Str => json!({"type": "string"}),
        Ty::Bytes => json!({"type": "string", "contentEncoding": "base64"}),
        Ty::String => json!({"type": ["string", "null"]}),
    }
}

/// OpenAPI 3.1 document: every FFI function is also a JSON operation, so the Rust servers expose
/// the same contract over HTTP.
#[must_use]
pub fn emit_openapi(c: &Contract) -> String {
    use serde_json::{Map, Value, json};
    let mut paths = Map::new();
    for f in &c.functions {
        let path = format!("/ffi/{}", f.name.trim_start_matches("rg_").replace('_', "-"));
        let mut props = Map::new();
        let mut required = Vec::new();
        for a in &f.args {
            props.insert(a.name.clone(), json_schema(a.ty));
            required.push(Value::String(a.name.clone()));
        }
        let op = json!({
            "operationId": camel(&f.name),
            "summary": f.doc,
            "x-ffi-symbol": f.name,
            "requestBody": {"required": true, "content": {"application/json": {"schema": {"type": "object", "properties": props, "required": required, "additionalProperties": false}}}},
            "responses": {"200": {"description": "Result", "content": {"application/json": {"schema": {"type": "object", "properties": {"result": json_schema(f.returns)}, "required": ["result"]}}}}}
        });
        paths.insert(path, json!({ "post": op }));
    }
    let doc = json!({
        "openapi": "3.1.0",
        "info": {"title": c.title, "version": c.version, "description": "Generated from crates/rg-ffi-contract/contract.json"},
        "paths": paths
    });
    let mut text = serde_json::to_string_pretty(&doc).expect("serialize");
    text.push('\n');
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn contract_is_valid_and_complete() {
        let c = load();
        assert!(c.functions.len() >= 8);
        let h = emit_c_header(&c);
        for f in &c.functions {
            assert!(h.contains(&format!("{}(", f.name)), "{} in header", f.name);
        }
        assert!(h.contains("rg_string_free") && h.contains("RG_FFI_ABI_VERSION 1u"));
    }

    #[test]
    fn ts_names_are_camel_case() {
        assert_eq!(camel("rg_elo_expected_score"), "eloExpectedScore");
        assert_eq!(camel("season_k"), "seasonK");
    }

    #[test]
    fn openapi_has_one_operation_per_function() {
        let c = load();
        let v: serde_json::Value = serde_json::from_str(&emit_openapi(&c)).unwrap();
        assert_eq!(v["paths"].as_object().unwrap().len(), c.functions.len());
        assert_eq!(v["openapi"], "3.1.0");
    }
}
