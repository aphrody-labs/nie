use std::{collections::BTreeMap, fmt::Write as _, path::Path};

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};

use crate::{
    config::{Mode, Sources, Spec},
    fetch::{Fetcher, extract},
};

#[derive(Debug, Serialize, Deserialize)]
pub struct Lock {
    pub specs: Vec<LockSpec>,
}

#[derive(Debug, Serialize, Deserialize)]
pub struct LockSpec {
    pub id: String,
    pub title: String,
    pub official: String,
    pub version: String,
    pub version_date: Option<String>,
    pub commit: Option<LockCommit>,
    pub sources: Vec<LockSource>,
    pub facts: Vec<LockFact>,
}

#[derive(Debug, Serialize, Deserialize)]
pub struct LockCommit {
    pub repo: String,
    pub sha: String,
    pub date: String,
}

#[derive(Debug, Serialize, Deserialize)]
pub struct LockSource {
    pub url: String,
    pub mode: Mode,
    pub sha256: String,
    pub bytes: usize,
}

#[derive(Debug, Serialize, Deserialize)]
pub struct LockFact {
    pub key: String,
    pub what: String,
    pub value: String,
    pub url: String,
}

/// Resolve every spec; returns the lock and the errors of the facts that failed.
pub fn resolve(sources: &Sources, only: &[String]) -> Result<(Lock, Vec<String>)> {
    let mut fetcher = Fetcher::new()?;
    let mut errors = Vec::new();
    let mut specs = Vec::new();
    for spec in sources
        .spec
        .iter()
        .filter(|s| only.is_empty() || only.contains(&s.id))
    {
        match resolve_one(&mut fetcher, spec, &mut errors) {
            Ok(s) => specs.push(s),
            Err(e) => errors.push(format!("{}: {e:#}", spec.id)),
        }
    }
    Ok((Lock { specs }, errors))
}

fn resolve_one(f: &mut Fetcher, spec: &Spec, errors: &mut Vec<String>) -> Result<LockSpec> {
    let mut sources: BTreeMap<(String, Mode), (String, usize)> = BTreeMap::new();
    let doc = f.doc(&spec.version.url, spec.version.mode)?;
    sources.insert(
        (spec.version.url.clone(), spec.version.mode),
        (doc.sha256.clone(), doc.bytes),
    );
    let re = regex::Regex::new(&spec.version.pattern).context("version pattern")?;
    let caps = re
        .captures(&doc.content)
        .with_context(|| format!("version pattern did not match on {}", spec.version.url))?;
    let date_group = caps.name("date");
    let labels: Vec<&str> = re
        .capture_names()
        .enumerate()
        .skip(1)
        .filter(|(_, n)| *n != Some("date"))
        .filter_map(|(i, _)| caps.get(i).map(|m| m.as_str()))
        .collect();
    let version = if labels.is_empty() {
        date_group.map_or_else(String::new, |m| m.as_str().to_owned())
    } else {
        labels.join(".")
    };
    let version_date = date_group
        .filter(|_| !labels.is_empty())
        .map(|m| m.as_str().to_owned());

    let commit = match &spec.commit {
        Some(c) => {
            let (sha, date) = f.latest_commit(&c.repo, c.path.as_deref(), c.branch.as_deref())?;
            Some(LockCommit {
                repo: c.repo.clone(),
                sha,
                date,
            })
        }
        None => None,
    };

    let mut facts = Vec::new();
    for fact in &spec.fact {
        let value = match (&fact.release_repo, &fact.pattern) {
            (Some(repo), _) => f
                .latest_release(repo)
                .map(|(tag, date)| format!("{tag} ({date})")),
            (None, Some(p)) => f.doc(&fact.url, fact.mode).and_then(|d| {
                sources.insert((fact.url.clone(), fact.mode), (d.sha256.clone(), d.bytes));
                extract(&d.content, p, &fact.join)
            }),
            (None, None) => Err(anyhow::anyhow!("no pattern and no release_repo")),
        };
        match value {
            Ok(value) => facts.push(LockFact {
                key: fact.key.clone(),
                what: fact.what.clone(),
                value,
                url: fact.url.clone(),
            }),
            Err(e) => errors.push(format!("{}.{}: {e:#}", spec.id, fact.key)),
        }
    }

    Ok(LockSpec {
        id: spec.id.clone(),
        title: spec.title.clone(),
        official: spec.official.clone(),
        version,
        version_date,
        commit,
        sources: sources
            .into_iter()
            .map(|((url, mode), (sha256, bytes))| LockSource {
                url,
                mode,
                sha256,
                bytes,
            })
            .collect(),
        facts,
    })
}

/// Markdown of one spec: links and short facts only.
pub fn render_spec(spec: &LockSpec, cfg: &Spec) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "<!-- Generated by `nie-specs sync` from sources.toml; do not edit. -->\n"
    );
    let _ = writeln!(s, "# {}\n", spec.title);
    let _ = writeln!(s, "- Official source: <{}>", spec.official);
    let date = spec
        .version_date
        .as_deref()
        .map_or(String::new(), |d| format!(" ({d})"));
    let _ = writeln!(s, "- Version: {}{date}", spec.version);
    if let Some(c) = &spec.commit {
        let _ = writeln!(
            s,
            "- Upstream commit: [`{}`](https://github.com/{}/commit/{}) on {}",
            &c.sha[..12.min(c.sha.len())],
            c.repo,
            c.sha,
            c.date
        );
    }
    if !cfg.used_by.is_empty() {
        let _ = writeln!(s, "- Used by: {}", cfg.used_by);
    }
    let _ = writeln!(
        s,
        "\n## Facts nie relies on\n\n| Fact | Value | Source |\n|---|---|---|"
    );
    for f in &spec.facts {
        let _ = writeln!(
            s,
            "| {} (`{}`) | `{}` | [page]({}) |",
            f.what,
            f.key,
            f.value.replace('|', "\\|"),
            f.url
        );
    }
    let _ = writeln!(
        s,
        "\n## Content hashes\n\nSHA-256 of the normalized page (`text`: tags and scripts removed; `raw`: bytes).\n"
    );
    let _ = writeln!(s, "| Page | Mode | SHA-256 | Bytes |\n|---|---|---|---|");
    for src in &spec.sources {
        let mode = if src.mode == Mode::Raw { "raw" } else { "text" };
        let _ = writeln!(
            s,
            "| <{}> | {mode} | `{}` | {} |",
            src.url, src.sha256, src.bytes
        );
    }
    s
}

pub fn render_index(lock: &Lock) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "<!-- Generated by `nie-specs sync`; do not edit. -->\n");
    let _ = writeln!(s, "# Specs\n");
    let _ = writeln!(
        s,
        "Official specifications nie relies on, with version, content hash and the extracted facts. \
         Declarations live in `sources.toml`; `lock.json` is the machine-readable record. Refresh with \
         `nie-specs sync` (scheduled by `.github/workflows/specs.yml`). Host specs: [hosts.md](hosts.md).\n"
    );
    let _ = writeln!(
        s,
        "| Spec | Version | Upstream commit | Facts |\n|---|---|---|---|"
    );
    for sp in &lock.specs {
        let c = sp.commit.as_ref().map_or("-".to_owned(), |c| {
            format!("`{}`", &c.sha[..12.min(c.sha.len())])
        });
        let date = sp
            .version_date
            .as_deref()
            .map_or(String::new(), |d| format!(" ({d})"));
        let _ = writeln!(
            s,
            "| [{}]({}.md) | {}{date} | {c} | {} |",
            sp.title,
            sp.id,
            sp.version,
            sp.facts.len()
        );
    }
    let _ = writeln!(
        s,
        "\nGraphics stack decision: [gfx-stack-evaluation.md](gfx-stack-evaluation.md)."
    );
    s
}

/// Generated files as `(relative path, content)`.
pub fn render_all(sources: &Sources, lock: &Lock) -> Result<Vec<(String, String)>> {
    let mut out = Vec::new();
    for sp in &lock.specs {
        let cfg = sources
            .spec
            .iter()
            .find(|c| c.id == sp.id)
            .with_context(|| format!("spec {}", sp.id))?;
        out.push((format!("{}.md", sp.id), render_spec(sp, cfg)));
    }
    out.push(("README.md".into(), render_index(lock)));
    out.push((
        "lock.json".into(),
        serde_json::to_string_pretty(lock)? + "\n",
    ));
    Ok(out)
}

pub fn run(root: &Path, only: &[String], check: bool) -> Result<()> {
    let sources = Sources::load(&root.join("sources.toml"))?;
    let (mut lock, errors) = resolve(&sources, only)?;
    if !errors.is_empty() {
        for e in &errors {
            eprintln!("FAIL {e}");
        }
        bail!("{} spec fact(s) failed; nothing written", errors.len());
    }
    if !only.is_empty() {
        // Partial run: keep the entries of the other specs from the existing lock.
        if let Ok(old) = std::fs::read_to_string(root.join("lock.json"))
            && let Ok(old) = serde_json::from_str::<Lock>(&old)
        {
            let mut merged: Vec<LockSpec> = old
                .specs
                .into_iter()
                .filter(|s| !only.contains(&s.id))
                .collect();
            merged.append(&mut lock.specs);
            let order: Vec<&str> = sources.spec.iter().map(|s| s.id.as_str()).collect();
            merged.sort_by_key(|s| order.iter().position(|i| *i == s.id));
            lock.specs = merged;
        }
    }
    let files = render_all(&sources, &lock)?;
    let mut drift = Vec::new();
    for (rel, content) in &files {
        let path = root.join(rel);
        if std::fs::read_to_string(&path).ok().as_deref() != Some(content) {
            drift.push(rel.clone());
            if !check {
                std::fs::write(&path, content).with_context(|| path.display().to_string())?;
            }
        }
    }
    for rel in &drift {
        println!("{} {rel}", if check { "drift" } else { "wrote" });
    }
    println!(
        "{} spec(s), {} fact(s), {} file(s) changed",
        lock.specs.len(),
        lock.specs.iter().map(|s| s.facts.len()).sum::<usize>(),
        drift.len()
    );
    if check && !drift.is_empty() {
        bail!("specs out of date");
    }
    Ok(())
}
